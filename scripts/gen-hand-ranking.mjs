// Regenerates resources/js/flopzer/handRanking.js: the 169 starting hands ordered by their equity against one random
// hand (Monte Carlo, fixed seed so the file only changes when the evaluator does).
//   node scripts/gen-hand-ranking.mjs [samples per hand = 60000]
import { writeFileSync } from 'node:fs';
import { evaluate } from '../resources/js/flopzer/evaluator.js';
import { CLASS_COMBOS, CLASS_NAMES, COMBOS } from '../resources/js/flopzer/cards.js';

const SAMPLES = Number(process.argv[2] ?? 60000);
let seed = 20261102;
const rand = () => { seed |= 0; seed = (seed + 0x6D2B79F5) | 0; let t = Math.imul(seed ^ (seed >>> 15), 1 | seed); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };

const equity = CLASS_NAMES.map((name, k) => {
    const [a, b] = COMBOS[CLASS_COMBOS[k][0]];
    const deck = [];
    for (let c = 0; c < 52; c++) if (c !== a && c !== b) deck.push(c);
    let points = 0;
    const mine = [a, b, 0, 0, 0, 0, 0], theirs = [0, 0, 0, 0, 0, 0, 0];
    for (let n = 0; n < SAMPLES; n++) {
        for (let i = 0; i < 7; i++) { const j = i + Math.floor(rand() * (deck.length - i)); [deck[i], deck[j]] = [deck[j], deck[i]]; }
        theirs[0] = deck[0]; theirs[1] = deck[1];
        for (let i = 0; i < 5; i++) { mine[2 + i] = theirs[2 + i] = deck[2 + i]; }
        const s1 = evaluate(mine), s2 = evaluate(theirs);
        points += s1 > s2 ? 1 : (s1 === s2 ? 0.5 : 0);
    }
    return { name, eq: points / SAMPLES };
});

equity.sort((x, y) => y.eq - x.eq || x.name.localeCompare(y.name));
const order = equity.map((e) => e.name);
writeFileSync(new URL('../resources/js/flopzer/handRanking.js', import.meta.url),
    `// Generated by scripts/gen-hand-ranking.mjs: the 169 hands, strongest first by equity against a random hand.\nexport const HAND_RANKING = ${JSON.stringify(order)};\n`);
console.log(equity.slice(0, 8).map((e) => `${e.name} ${(100 * e.eq).toFixed(1)}%`).join('  '), '...', equity.slice(-3).map((e) => `${e.name} ${(100 * e.eq).toFixed(1)}%`).join('  '));
